from errand_agent.tools import ScenarioConfig, ToolEnvironment


class EvalClock:
    def __init__(self, t: float = 1_700_000_000.0):
        self.t = t

    def __call__(self) -> float:
        self.t += 0.005
        return self.t

    def advance(self, seconds: float) -> None:
        self.t += seconds


@dataclass
class ScenarioResult:
    scenario_id: str
    name: str
    expected: str
    actual: str
    passed: bool
    notes: str


def make_harness(
    force_book_outcome: str | None = "success",
    token_budget: int = 450,
    limits: ExecutionLimits | None = None,
) -> tuple[EvalClock, ErrandStore, ScenarioConfig, ToolEnvironment, ErrandAgent]:
    clock = EvalClock()
    store = ErrandStore(":memory:", clock=clock)
    cfg = ScenarioConfig(seed=42, force_book_outcome=force_book_outcome)
    env = ToolEnvironment(store, cfg, default_user_id="user_01")
    agent = ErrandAgent(
        store,
        env,
        user_id="user_01",
        session_id="sess_eval",
        limits=limits,
        token_budget=token_budget,
    )
    return clock, store, cfg, env, agent


