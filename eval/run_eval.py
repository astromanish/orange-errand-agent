def s10_timeout_after_possible_success_actually_booked() -> ScenarioResult:
    """Also writes the canonical raw trace deliverable to `traces/timeout_after_success_trace.json`."""
    _, store, _, env, agent = make_harness(force_book_outcome="timeout_booked")
    seed_fifty_plus_memories_and_long_history(store, user_id="user_01", session_id=agent.session_id)
    t1 = agent.handle_turn("Find a plumber in Indiranagar for my kitchen tap this week, mornings only, under ₹1,500.")
    t2 = agent.handle_turn("Yes, confirm")
    bks = env.list_bookings("user_01")["bookings"]
    traces = store.get_traces(agent.session_id)

    # Save canonical end-to-end raw trace for Deliverable #5
    trace_path = ROOT / "traces" / "timeout_after_success_trace.json"
    trace_path.parent.mkdir(parents=True, exist_ok=True)
