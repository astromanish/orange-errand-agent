"""Automated 22-scenario offline evaluation harness with simulated users.

Generates:
1. `EVAL_RESULTS.md` — Markdown table (`scenario · expected · actual · pass/fail · notes`)
   auto-generated by the test run (Deliverable #3).
2. `traces/timeout_after_success_trace.json` — Raw end-to-end trace file for a run
   that includes a timeout-after-success resolved via `get_booking_status` (Deliverable #5).
"""
from __future__ import annotations

