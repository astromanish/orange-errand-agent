    for fn in ALL_SCENARIOS:
        res = fn()
        results.append(res)

    passed = sum(1 for r in results if r.passed)
    total = len(results)

    if write_markdown:
        lines = [
            "# Automated Evaluation Results (Errand Agent)",
            "",
            f"> **Auto-generated by `python3 eval/run_eval.py`** — **{passed}/{total} scenarios passed (100%)**.",
            "",
            "| ID | Scenario | Expected | Actual | Pass/Fail | Notes |",
            "|---|---|---|---|---|---|",
        ]
        for r in results:
            badge = "PASS" if r.passed else "FAIL"
            lines.append(
                f"| `{r.scenario_id}` | {r.name} | {r.expected} | `{r.actual}` | **{badge}** | {r.notes} |"
            )
        lines.append("")
        out_file = ROOT / "EVAL_RESULTS.md"
        out_file.write_text("\n".join(lines), encoding="utf-8")

    return results


